  ex[1]={a:N,p:ver.filter(p=>p.attribution!==null&&p.attribution<=1).length,d:false,ev:''};
  ex[2]={a:N,p:countP(RE.ex2),d:false,ev:ev(RE.ex2)};
  ex[3]={a:N,p:countP(RE.ex3),d:false,ev:ev(RE.ex3)};
  ex[4]={a:N,p:countP(RE.ex4),d:false,ev:ev(RE.ex4)};
  const t5=has(RE.ex5,fold(whole)),t8=has(RE.ex8,fold(whole));
  ex[5]={a:t5?1:0,p:t5?1:0,d:false,ev:t5?ev(RE.ex5):''};
