function analyze(part,SEL){
  const text=norm(part);
  const segs=segment(text);
  const allowed=SEL?new Set(SEL.map(d=>d.c)):null;
  const passages=segs.map(codePassage);
  const exits=exitsOf(passages,text);
  const flags=[];
  const f=fold(text);
  for(const m of allMatches(RE.cred,f).slice(0,6))flags.push({c:10,quote:text.slice(m.i,m.i+m.t.length),why:'عبارة مصداقية استباقية'});
  passages.forEach(p=>{
    if(allowed)p.indicators=p.indicators.filter(i=>allowed.has(i.c));
    delete p._f;
  });
  return {passages,exits,flags};
}

