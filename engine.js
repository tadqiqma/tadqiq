function segment(t){
  const sents=t.split(/(?<=[.!؟?…؛])\s+/).map(x=>x.trim()).filter(Boolean);
  const out=[];let cur=[],words=0;
  const flush=()=>{if(cur.length){out.push(cur.join(' '));cur=[];words=0}};
  for(const s of sents){
    const w=s.split(' ').length;
    if(cur.length&&(words+w>60||cur.length>=3||words>=24))flush();
    cur.push(s);words+=w;
    if(w>60)flush();
  }
  flush();
  return out.filter(p=>p.split(' ').length>=5);
}

